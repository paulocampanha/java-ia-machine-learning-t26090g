/*
Nesse programa vamos estudar as arrays (vetores) em java
*/
public class Vetor {
    public static void main(String args[]){
        
        int[] numeros = {10, 15, 20, 25};
        String[] nomes = {
            "Anabela", "Gaspar", "Jorge", "Luiza"
        };

        System.out.println(nomes[0] + " tem " + numeros[0] + " anos.");
        System.out.println(nomes[1] + " tem " + numeros[1] + " anos.");
        System.out.println(nomes[2] + " tem " + numeros[2] + " anos.");
        System.out.println(nomes[3] + " tem " + numeros[3] + " anos.");
    }
}
